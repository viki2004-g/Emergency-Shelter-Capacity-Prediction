"""
services/redistribution.py — Multi-shelter redistribution engine.

When an incoming evacuee group cannot safely fit into a single eligible shelter,
this service partitions the group across multiple eligible shelters according to:
  1. Operational status
  2. Safe available capacity limits (never exceeded)
  3. Special demographic & facility requirements (wheelchair, medical)
  4. Predicted future occupancy load (overload risk penalties)
  5. Multi-criteria ranking (proximity, capacity, facilities, resources)

Key Guarantees:
  - Zero safe capacity overruns: No shelter receives > safe_available_capacity.
  - Strict verification assertion: allocated_people == requested_people.
  - Transparent deficit explanation if redistribution is impossible.
  - Occupancy is NEVER mutated until an explicit confirmation action is executed.
"""

from datetime import datetime
from typing import List, Dict, Any, Optional, Tuple
from extensions import db
from models.shelter import Shelter
from models.request import ShelterRequest
from models.allocation import Allocation
from models.occupancy import OccupancyHistory
from services.distance import haversine_distance, distance_band, BAND_LABELS
from services.prediction import predict_shelter_occupancy
from services.scoring import (
    get_configured_weights,
    calculate_distance_score,
    calculate_capacity_score,
    calculate_facilities_score,
    calculate_resources_score,
    calculate_weighted_score,
)

DISCLAIMER_TEXT = (
    "Redistribution allocation plan generated by deterministic heuristic multi-criteria ranking. "
    "All allocations respect designated safe planning thresholds. "
    "Field coordinators must confirm on-ground transit logistics before executing physical dispatch."
)


def plan_group_redistribution(
    request: Any,
    shelters: Optional[List[Shelter]] = None,
    custom_weights: Optional[Dict[str, float]] = None,
    hours_ahead: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Computes a multi-shelter redistribution plan for an incoming group.

    Args:
        request:        ShelterRequest model instance or duck-typed synthetic request.
        shelters:       Optional list of Shelter models. If None, queries all.
        custom_weights: Optional weight dictionary overriding config defaults.
        hours_ahead:    Optional forecast horizon for future occupancy prediction.

    Returns:
        dict containing:
          is_possible                 : bool (True if allocated == requested)
          total_requested             : int (group_size)
          total_allocated             : int
          unallocated_count           : int (group_size - total_allocated)
          total_network_safe_capacity : int (sum of safe available across candidates)
          allocations                 : list of allocation dictionaries
          candidate_shelters          : list of ranked candidate shelters
          unsuitable_shelters         : list of disqualified shelters with reasons
          explanation                 : human-readable summary or deficit report
          disclaimer                  : string notice
          request                     : the original request object
    """
    # ── Step 1: Discover candidate shelters ───────────────────────────────────
    if shelters is None:
        shelters = Shelter.query.all()

    # Extract request attributes safely
    group_size = int(getattr(request, 'group_size', 1) or 1)
    group_size = max(1, group_size)

    req_lat = float(getattr(request, 'latitude',  0.0) or 0.0)
    req_lon = float(getattr(request, 'longitude', 0.0) or 0.0)

    needs_wheelchair = (
        bool(getattr(request, 'has_disabled', False)) or
        bool(
            getattr(request, 'accessibility_requirements', None) and
            str(request.accessibility_requirements).strip()
        )
    )

    injured_cnt = int(getattr(request, 'injured_count', 0) or 0)
    needs_medical = (
        bool(getattr(request, 'has_injured', False)) or
        (injured_cnt > 0) or
        bool(
            getattr(request, 'medical_requirements', None) and
            str(request.medical_requirements).strip()
        )
    )

    weights = get_configured_weights(custom_weights)

    unsuitable_shelters: List[Dict[str, Any]] = []
    suitable_candidates: List[Dict[str, Any]] = []

    # ── Step 2 & 3: Filter unsuitable shelters & compute safe capacities ───────
    for shelter in shelters:
        # Check operational status
        if shelter.status != 'active':
            unsuitable_shelters.append({
                'shelter': shelter,
                'reason': (
                    f"Shelter status is '{shelter.status_label}' — "
                    f"only Active shelters can accept evacuees."
                ),
                'category': 'status',
            })
            continue

        # Check safe available capacity
        safe_avail = shelter.safe_available_capacity
        if safe_avail <= 0:
            unsuitable_shelters.append({
                'shelter': shelter,
                'reason': (
                    f"No safe capacity headroom available ({shelter.current_occupancy}/"
                    f"{shelter.safe_capacity} safe spots occupied)."
                ),
                'category': 'capacity',
            })
            continue

        facility = getattr(shelter, 'facility', None)

        # Check wheelchair hard constraint
        if needs_wheelchair:
            if not facility or not facility.has_wheelchair_access:
                unsuitable_shelters.append({
                    'shelter': shelter,
                    'reason': "Lacks wheelchair-accessible infrastructure required by this group.",
                    'category': 'wheelchair',
                })
                continue

        # Check medical hard constraint
        if needs_medical:
            if not facility or not facility.has_medical_support:
                unsuitable_shelters.append({
                    'shelter': shelter,
                    'reason': "Lacks on-site medical facility / medical support required for injured evacuees.",
                    'category': 'medical',
                })
                continue

        # ── Step 4 & 5: Facilities, distance & predicted future load ──────────
        shelter_lat = float(shelter.latitude  or 0.0)
        shelter_lon = float(shelter.longitude or 0.0)
        dist_km = haversine_distance(req_lat, req_lon, shelter_lat, shelter_lon)
        band = distance_band(dist_km)
        dist_label = BAND_LABELS.get(band, 'Accessible distance')

        # Future occupancy forecast heuristic
        prediction = predict_shelter_occupancy(shelter, hours_ahead=hours_ahead)

        # Component scoring
        score_dist = calculate_distance_score(dist_km)
        score_cap  = calculate_capacity_score(shelter, safe_avail, prediction)
        score_fac  = calculate_facilities_score(shelter, request)
        score_res  = calculate_resources_score(shelter, request)

        score_data = calculate_weighted_score(
            dist_score=score_dist,
            cap_score=score_cap,
            fac_score=score_fac,
            res_score=score_res,
            weights=weights,
        )
        base_score = score_data['total_score']

        # Adjust score for predicted future load risk
        penalty = 0.0
        if prediction.get('has_prediction'):
            risk = prediction.get('overload_risk', 'low')
            if risk == 'critical':
                penalty = 35.0  # Heavy penalty for shelter predicted to reach 100%
            elif risk == 'high':
                penalty = 15.0  # Moderate penalty for shelter exceeding safe limit
            elif risk == 'low':
                penalty = -5.0  # Small bonus for low-risk shelter

        final_score = round(max(0.0, min(100.0, base_score - penalty)), 2)

        suitable_candidates.append({
            'shelter':                 shelter,
            'shelter_id':              shelter.id,
            'name':                    shelter.name,
            'address':                 shelter.address,
            'safe_available_capacity': safe_avail,
            'current_occupancy':       shelter.current_occupancy,
            'safe_capacity':           shelter.safe_capacity,
            'max_capacity':            shelter.max_capacity,
            'safe_limit_pct':          shelter.safe_limit,
            'occupancy_pct':           shelter.occupancy_pct,
            'distance_km':             dist_km,
            'distance_band':           band,
            'distance_label':          dist_label,
            'prediction':              prediction,
            'score':                   final_score,
            'base_score':              base_score,
            'score_components':        score_data['components'],
            'facility':                facility,
            'resource':                getattr(shelter, 'resource', None),
        })

    # ── Step 6: Rank candidate shelters ───────────────────────────────────────
    # Higher score first; ties broken by shortest distance, then largest capacity
    suitable_candidates.sort(
        key=lambda c: (-c['score'], c['distance_km'], -c['safe_available_capacity'])
    )

    for i, c in enumerate(suitable_candidates, 1):
        c['rank'] = i

    # ── Step 7 & 8: Priority allocation loop enforcing safe capacity ──────────
    remaining_needed = group_size
    allocations: List[Dict[str, Any]] = []

    for cand in suitable_candidates:
        if remaining_needed <= 0:
            break

        safe_avail = cand['safe_available_capacity']
        alloc_count = min(safe_avail, remaining_needed)

        if alloc_count > 0:
            remaining_needed -= alloc_count
            safe_after = safe_avail - alloc_count
            post_occ = cand['current_occupancy'] + alloc_count
            post_pct = round((post_occ / cand['max_capacity']) * 100, 1) if cand['max_capacity'] > 0 else 0.0

            reasons = [
                f"Allocated {alloc_count} evacuee(s) (safe headroom: {safe_avail} available, {safe_after} remaining)",
                f"{cand['distance_label']}: {cand['distance_km']} km from incident site",
                f"Ranking Score: {cand['score']}/100 (#Rank {cand['rank']})",
            ]
            pred = cand['prediction']
            if pred.get('has_prediction'):
                reasons.append(
                    f"[ESTIMATE] Predicted occupancy {pred.get('predicted_pct')}% in {pred.get('hours_ahead', 6)}h "
                    f"({pred.get('risk_label')} risk)"
                )

            allocations.append({
                'shelter':                cand['shelter'],
                'shelter_id':             cand['shelter_id'],
                'shelter_name':           cand['name'],
                'shelter_address':        cand['address'],
                'allocated_count':        alloc_count,
                'current_occupancy':      cand['current_occupancy'],
                'safe_capacity':          cand['safe_capacity'],
                'max_capacity':           cand['max_capacity'],
                'safe_available_before':  safe_avail,
                'safe_available_after':   safe_after,
                'projected_occupancy':    post_occ,
                'projected_pct':          post_pct,
                'distance_km':            cand['distance_km'],
                'distance_label':         cand['distance_label'],
                'score':                  cand['score'],
                'rank':                   cand['rank'],
                'prediction':             pred,
                'reasons':                reasons,
                'facility':               cand['facility'],
                'resource':               cand['resource'],
            })

    # ── Step 9: Verification assertion & plan synthesis ───────────────────────
    total_allocated = sum(a['allocated_count'] for a in allocations)
    is_possible = (total_allocated == group_size)
    unallocated_count = group_size - total_allocated
    total_net_safe_cap = sum(c['safe_available_capacity'] for c in suitable_candidates)

    if is_possible:
        explanation = (
            f"Successfully partitioned all {group_size} evacuees across {len(allocations)} shelter(s). "
            f"Every allocation respects safe capacity limits without breaching planning thresholds."
        )
    else:
        explanation = (
            f"Redistribution impossible: Available network safe capacity ({total_net_safe_cap}) "
            f"across {len(suitable_candidates)} eligible shelter(s) is insufficient for requested group of {group_size}. "
            f"Deficit of {unallocated_count} evacuee(s) cannot be safely accommodated under current safe planning limits."
        )

    return {
        'is_possible':                 is_possible,
        'total_requested':             group_size,
        'total_allocated':             total_allocated,
        'unallocated_count':           unallocated_count,
        'total_network_safe_capacity': total_net_safe_cap,
        'allocations':                 allocations,
        'candidate_shelters':          suitable_candidates,
        'unsuitable_shelters':         unsuitable_shelters,
        'explanation':                 explanation,
        'disclaimer':                  DISCLAIMER_TEXT,
        'request':                     request,
        'weights_used':                weights,
    }


def execute_confirmed_allocation(
    request_id: int,
    plan: Dict[str, Any],
    confirmed_by_user_id: Optional[int] = None,
    notes: Optional[str] = None,
) -> Tuple[bool, List[Allocation]]:
    """
    Executes and commits an approved redistribution allocation inside an atomic transaction.
    Delegates directly to services.allocation.confirm_allocation to enforce pessimistic
    locking, deadlock avoidance, real-time safe capacity verification, and complete rollback safety.

    Args:
        request_id:           ID of the ShelterRequest being allocated.
        plan:                 Redistribution plan dictionary from plan_group_redistribution.
        confirmed_by_user_id: ID of the responder/admin confirming the action.
        notes:                Optional audit notes.

    Returns:
        (success: bool, created_allocations: List[Allocation])
    """
    from services.allocation import confirm_allocation
    if not plan or not plan.get('allocations'):
        raise ValueError("Cannot confirm an empty allocation plan.")

    alloc_result = confirm_allocation(
        request_id=request_id,
        allocations=plan.get('allocations', []),
        confirmed_by_user_id=confirmed_by_user_id,
        notes=notes,
    )
    return alloc_result['success'], alloc_result['allocations']
